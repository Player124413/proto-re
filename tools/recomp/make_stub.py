#!/usr/bin/env python3
"""Writes a stub replacement for the recompiled-engine output (table.c only).

The real generated code comes from the user's own prototypeenginef.dll
(tools/recomp/recomp.py) and is never in this repository, so CI cannot build a
playable engine. This stub provides the symbols src/native links against
(g_recomp_table/g_recomp_count, plus g_recomp_entries for the Wine bridge)
with a single entry that traps through RecompUnimplemented. It contains no
game code: APKs linked against it only prove that the whole Android pipeline
(deps, Java, runtime, packaging, signing) builds. They are NOT playable.

Usage:
  python3 tools/recomp/make_stub.py [out dir]     (default: build/recomp/native)
"""
import os
import sys

TABLE_C = """/* CI stub generated by tools/recomp/make_stub.py; do not edit.
 * NO recompiled engine code: every guest call traps as unimplemented. */
#include <math.h>
#include "runtime.h"
#include "runtime_fp.h"

static void ProtoreCiStub(Ctx* c) {
    RecompUnimplemented(c, 0, "CI stub build: no recompiled engine code (tools/recomp/make_stub.py)");
}

const struct { uint32_t va; RecompFn fn; } g_recomp_table[] = {
    {0x58000000u, ProtoreCiStub},
};
const uint32_t g_recomp_count = sizeof(g_recomp_table) / sizeof(g_recomp_table[0]);

/* Only the in-process Wine bridge reads these; the native host needs none. */
const struct { uint32_t va; uint8_t len; int8_t rel32_at; uint8_t bytes[15]; } g_recomp_entries[] = {
    {0x58000000u, 0, -1, {0}},
};
const uint32_t g_recomp_entry_count = 0;
"""


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "build/recomp/native"
    os.makedirs(out_dir, exist_ok=True)
    # Never mix with a previous real run of recomp.py in the same directory:
    # the Makefile compiles every *.c it finds there.
    removed = 0
    for name in os.listdir(out_dir):
        if name.startswith("part_") and name.endswith(".c"):
            os.remove(os.path.join(out_dir, name))
            removed += 1
    with open(os.path.join(out_dir, "table.c"), "w") as f:
        f.write(TABLE_C)
    print(f"stub recomp table written to {out_dir}/table.c"
          + (f" (removed {removed} stale part_*.c)" if removed else ""))


if __name__ == "__main__":
    main()
